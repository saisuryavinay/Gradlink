import JobApplication from '../models/JobApplication.js';
import PDFDocument from 'pdfkit';

// GET /api/applications/:id/pdf — student downloads their own application PDF
export const downloadApplicationPDF = async (req, res, next) => {
  try {
    const app = await JobApplication.findOne({
      _id: req.params.id,
      student: req.user._id,
    }).populate('job', 'company title deadline').populate('student', 'name email department graduationYear');

    if (!app) return res.status(404).json({ message: 'Application not found.' });

    const doc = new PDFDocument({ margin: 50 });
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename=application_${app._id}.pdf`);
    doc.pipe(res);

    doc.fontSize(20).fillColor('#1D4ED8').text('GradLink — Application Summary', { align: 'center' });
    doc.moveDown(0.5);
    doc.moveTo(50, doc.y).lineTo(560, doc.y).stroke('#CBD5E1');
    doc.moveDown(0.5);

    const field = (label, value) => {
      if (!value && value !== 0) return;
      doc.fontSize(11).fillColor('#374151').font('Helvetica-Bold').text(`${label}: `, { continued: true });
      doc.font('Helvetica').fillColor('#111827').text(String(value));
    };

    doc.fontSize(14).fillColor('#1E40AF').font('Helvetica-Bold').text('Applicant Information');
    doc.moveDown(0.3);
    field('Name', app.student?.name);
    field('Department', app.student?.department);
    field('Graduation Year', app.student?.graduationYear);
    doc.moveDown();

    doc.fontSize(14).fillColor('#1E40AF').font('Helvetica-Bold').text('Job Details');
    doc.moveDown(0.3);
    field('Company', app.job?.company);
    field('Position', app.job?.title);
    field('Deadline', app.job?.deadline ? new Date(app.job.deadline).toLocaleDateString() : 'N/A');
    doc.moveDown();

    doc.fontSize(14).fillColor('#1E40AF').font('Helvetica-Bold').text('Application Status');
    doc.moveDown(0.3);
    field('Status', app.status.charAt(0).toUpperCase() + app.status.slice(1));
    field('Submitted On', new Date(app.submittedAt).toLocaleDateString());
    doc.moveDown();

    if (app.formData?.size > 0) {
      doc.fontSize(14).fillColor('#1E40AF').font('Helvetica-Bold').text('Submitted Information');
      doc.moveDown(0.3);
      for (const [key, value] of app.formData.entries()) {
        field(key, value);
      }
    }

    doc.moveDown(2);
    doc.fontSize(10).fillColor('#9CA3AF').text(`Generated by GradLink on ${new Date().toLocaleDateString()}`, { align: 'center' });

    doc.end();
  } catch (error) {
    next(error);
  }
};
